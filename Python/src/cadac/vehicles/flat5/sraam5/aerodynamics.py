def _mach_alpha(flat):
    """Fortran TABL2 layout: alpha-major rows of 14 mach → values[mach, alpha]."""
    return np.asarray(flat, dtype=float).reshape(len(_ALPHA), len(_MACH)).T


def _mach_alpha_x(flat, nx):
    """Fortran TABL3 layout: nx slices of (alpha × mach) → values[mach, alpha, x]."""
    arr = np.asarray(flat, dtype=float).reshape(nx, len(_ALPHA), len(_MACH))
    return arr.transpose(2, 1, 0)


def _build_deck():
    return Datadeck.from_tables(
        [
            Table("cd_on", 3, _MACH, _ALPHA, _XCG_AERO, _mach_alpha_x(_ATBLON, 3)),
            Table("cd_off", 2, _MACH, _ALPHA, None, _mach_alpha(_ATBLOF)),
            Table("cl_on", 3, _MACH, _ALPHA, _XCG_AERO, _mach_alpha_x(_TNTBL1, 3)),
            Table("cl_off", 2, _MACH, _ALPHA, None, _mach_alpha(_TNTBL2)),
            Table("csfc", 3, _MACH, _ALPHA, _ALT_FT, _mach_alpha_x(_ATBLSF, 4)),
            Table(
                "alpmax",
                2,
                _MACH,
                _XCG_ALPMAX,
                None,
                np.asarray(_AMXTBL, dtype=float).reshape(len(_XCG_ALPMAX), len(_MACH)).T,
            ),
        ]
    )


_DECK = _build_deck()


class Sraam5Aerodynamics:
    name = "aerodynamics"

    def __init__(self, deck=None):
        self.deck = deck if deck is not None else _DECK

    def define(self, vehicle):
        store = vehicle.store
        plot = ("plot",)
        scrn_plot = ("scrn", "plot")
        for field in (
            Field("area", 0.0, "real", "data", "aerodynamics"),
            Field("ca", 0.0, "real", "out", "aerodynamics"),
            Field("cn", 0.0, "real", "out", "aerodynamics"),
            Field("cy", 0.0, "real", "out", "aerodynamics"),
            Field("cnalp", 0.0, "real", "out", "aerodynamics"),
            Field("cybet", 0.0, "real", "out", "aerodynamics"),
            Field("cmdel", 0.0, "real", "out", "aerodynamics"),
            Field("gmax", 0.0, "real", "out", "aerodynamics", plot),
            Field("gavail", 0.0, "real", "diag", "aerodynamics", plot),
            Field("cdt", 0.0, "real", "diag", "aerodynamics"),
            Field("csfc", 0.0, "real", "diag", "aerodynamics"),
            Field("cd", 0.0, "real", "diag", "aerodynamics"),
            Field("clt", 0.0, "real", "diag", "aerodynamics"),
            Field("alpmax", 0.0, "real", "diag", "aerodynamics"),
            Field("alphapx", 0.0, "real", "diag", "aerodynamics"),
            Field("phipp", 0.0, "real", "diag", "aerodynamics"),
            Field("alift", 0.0, "real", "diag", "aerodynamics"),
            Field("adrag", 0.0, "real", "diag", "aerodynamics"),
            Field("trcode", 0.0, "real", "diag", "aerodynamics", scrn_plot),
            Field("tmcode", 0.0, "real", "data", "aerodynamics"),
            Field("trcvel", 0.0, "real", "data", "aerodynamics"),
            Field("trmach", 0.0, "real", "data", "aerodynamics"),
            Field("trdynm", 0.0, "real", "data", "aerodynamics"),
            Field("trload", 0.0, "real", "data", "aerodynamics"),
            Field("tralp", 0.0, "real", "data", "aerodynamics"),
            Field("trtht", 0.0, "real", "data", "aerodynamics"),
            Field("trthtd", 0.0, "real", "data", "aerodynamics"),
            Field("trphid", 0.0, "real", "data", "aerodynamics"),
            Field("trate", 0.0, "real", "data", "aerodynamics"),
        ):
            if field.name not in store:
                store.define(field)

    def initialize(self, vehicle, ctx):
        store = vehicle.store
        optmet = store.get("optmet") if "optmet" in store else 0.0
        store.set("cnalp", 8.0)
        store.set("cybet", -8.0)
        store.set("cmdel", 78.0)
        store.set("phipp", 0.0)
        store.set("trcvel", 300.0 * (1.0 - 0.695 * optmet))
        store.set("trmach", 0.8)
        store.set("trdynm", 200.0 * (1.0 + 46.881 * optmet))
        store.set("trload", 3.0)
        store.set("tralp", 1.0)
        store.set("trtht", 1.57)
        store.set("trphid", 14.0)
        store.set("trthtd", 10.0)
        store.set("trate", 1.0)
        store.set("trcode", 0.0)
        store.set("tmcode", 0.0)

    def execute(self, vehicle, ctx):
        store = vehicle.store
        look_up = self.deck.look_up
        crad = DEG
        optmet = store.get("optmet") if "optmet" in store else 0.0
        agrav = store.get("agrav") if "agrav" in store else AGRAV
        pdynmc = store.get("pdynmc")
        vmach = store.get("vmach")
        alpha = store.get("alpha")
        beta = store.get("beta")
        anplim = store.get("anplim") if "anplim" in store else 50.0
        mprop = int(store.get("mprop"))
        amass = store.get("amass")
        xcgin = store.get("xcgin")
        area = store.get("area")
        hbe = store.get("hbe")
        trload = store.get("trload")
        tralp = store.get("tralp")
        trcode = store.get("trcode")

        alphap = acos(cos(alpha) * cos(beta))
        if abs(alphap) > tralp:
            trcode = 5.0

        dum1 = tan(beta)
        dum2 = sin(alpha)
        phipp = np.copysign(1.570796, beta)
        if abs(dum2) > 1.0e-10:
            phipp = atan2(dum1, dum2)

        alphapx = abs(alphap * crad)
        hbesk = hbe * (1.0 + 2.281 * optmet)

        if xcgin > 57.04:
            alpmax = 45.0
        else:
            alpmax = look_up("alpmax", vmach, xcgin)
        if alpmax > 0.0 and alphapx > alpmax:
            alphapx = alpmax

        csfc = look_up("csfc", vmach, alphapx, hbesk)
        if mprop == 0:
            cdt = look_up("cd_off", vmach, alphapx)
            clt = look_up("cl_off", vmach, alphapx)
        else:
            cdt = look_up("cd_on", vmach, alphapx, xcgin)
            clt = look_up("cl_on", vmach, alphapx, xcgin)
        cd = cdt + csfc

        alpx = abs(crad * alpha)
        betx = abs(crad * beta)
        if alpx <= 10.0:
            cnalp = crad * (0.123 + 0.013 * alpx)
        else:
            cnalp = crad * 0.06 * alpx**0.625
        if betx <= 10.0:
            cybet = -crad * (0.123 + 0.013 * betx)
        else:
            cybet = -crad * 0.06 * betx**0.625

        ca = cd * cos(alphapx / crad) - clt * sin(alphapx / crad)
        cn = cd * sin(alphapx / crad) + clt * cos(alphapx / crad)
        if alphap < 0.0:
            cn = -cn
        cy = -cn * sin(phipp)
        cn = cn * cos(phipp)

        if mprop == 0:
            cdmax = look_up("cd_off", vmach, alpmax)
            clmx = look_up("cl_off", vmach, alpmax)
        else:
            # Fortran A1 line uses ATBLOF with TABL3 (undersized); use ATBLON intent.
            cdmax = look_up("cd_on", vmach, alpmax, xcgin)
            clmx = look_up("cl_on", vmach, alpmax, xcgin)
        cdmx = cdmax + csfc
        cnmx = cdmx * sin(alpmax / crad) + clmx * cos(alpmax / crad)
        almx = cnmx * pdynmc * area
        weight = amass * agrav
        gmax = almx / weight
        if gmax < trload:
            trcode = 4.0
        if gmax > anplim:
            gmax = anplim
        altot = clt * pdynmc * area
        afac = altot / weight
        gavail = gmax - afac

        alift = clt * pdynmc * area * (1.0 + 3.45 * optmet)
        adrag = cd * pdynmc * area * (1.0 + 3.45 * optmet)

        store.set("ca", ca)
        store.set("cn", cn)
        store.set("cy", cy)
        store.set("cnalp", cnalp)
        store.set("cybet", cybet)
        store.set("gmax", gmax)
        store.set("gavail", gavail)
        store.set("cdt", cdt)
        store.set("csfc", csfc)
        store.set("cd", cd)
        store.set("clt", clt)
        store.set("alpmax", alpmax)
        store.set("alphapx", alphapx)
        store.set("phipp", phipp)
        store.set("alift", alift)
        store.set("adrag", adrag)
        store.set("trcode", trcode)

    def terminate(self, vehicle, ctx):
        pass
